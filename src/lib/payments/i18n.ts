export const MESSAGES: Record<Locale, Messages> = { en, es, pt, fr, de, hi, zh };

export function isLocale(code: unknown): code is Locale {
  return typeof code === "string" && LOCALES.some((l) => l.code === code);
}

/**
 * The visitor's language: an explicit `?lang=` first, then the cookie, then the first
 * Accept-Language entry we ship (matched on its base subtag), then English.
 */
export function resolveLocale(input: { query?: string | null; cookie?: string | null; acceptLanguage?: string | null }): Locale {
  if (isLocale(input.query)) return input.query;
  if (isLocale(input.cookie)) return input.cookie;
  const wanted = (input.acceptLanguage || "")
    .split(",")
    .map((part) => {
      const [tag, ...params] = part.trim().split(";");
      const q = params.map((p) => p.trim()).find((p) => p.startsWith("q="));
      return { base: tag.trim().toLowerCase().split("-")[0], q: q ? Number(q.slice(2)) || 0 : 1 };
    })
    .filter((x) => x.base && x.q > 0)
    .sort((a, b) => b.q - a.q);
  for (const { base } of wanted) if (isLocale(base)) return base;
  return DEFAULT_LOCALE;
}
